// ─── Professional summary generator ──────────────────────────────────────────

export function generateSummaryFromTitle(title: string): string {
  const t = title.toLowerCase();

  if (t.includes('frontend') || t.includes('front-end') || t.includes('ui developer')) {
    return `Results-driven frontend developer with a passion for building responsive, accessible, and high-performance web applications. Proficient in modern JavaScript frameworks and design systems, with a strong eye for detail and user experience. Committed to writing clean, maintainable code and collaborating closely with designers and backend teams to deliver polished products.`;
  }
  if (t.includes('backend') || t.includes('back-end') || t.includes('api developer') || t.includes('server-side')) {
    return `Experienced backend developer with expertise in designing and building scalable APIs, microservices, and data pipelines. Passionate about system architecture, security, and performance optimisation. Comfortable translating complex business requirements into robust, well-tested technical solutions.`;
  }
  if (t.includes('fullstack') || t.includes('full stack') || t.includes('full-stack')) {
    return `Versatile full-stack developer with end-to-end ownership across the entire web stack — from pixel-perfect frontend interfaces to scalable backend systems. Skilled at delivering features independently and collaborating in agile teams to ship high-quality products on time.`;
  }
  if (t.includes('mobile') || t.includes('ios') || t.includes('android') || t.includes('react native') || t.includes('flutter')) {
    return `Mobile developer specialising in building intuitive, performant applications for iOS and Android. Passionate about delivering seamless user experiences and optimising for device-specific constraints. Experienced in the full mobile development lifecycle from prototyping to App Store release.`;
  }
  if (t.includes('devops') || t.includes('cloud engineer') || t.includes('sre') || t.includes('platform engineer') || t.includes('infrastructure')) {
    return `DevOps engineer with a strong background in CI/CD pipelines, infrastructure-as-code, and cloud platforms. Passionate about improving developer experience, system reliability, and deployment velocity through automation, monitoring, and engineering best practices.`;
  }
  if (t.includes('data scientist') || t.includes('machine learning') || t.includes('ml engineer') || t.includes('ai engineer')) {
    return `Data scientist and ML practitioner with experience building predictive models, analysing large datasets, and deploying machine learning solutions to production. Skilled in Python, statistical modelling, and communicating data-driven insights to non-technical stakeholders to drive informed decisions.`;
  }
  if (t.includes('data analyst') || t.includes('business analyst') || t.includes('bi analyst')) {
    return `Detail-oriented data analyst with expertise in transforming raw data into actionable business insights. Proficient in SQL, Excel, and data visualisation tools. Experienced in collaborating with stakeholders across departments to understand requirements and deliver reports that drive strategic decision-making.`;
  }
  if (t.includes('data engineer')) {
    return `Data engineer with expertise in designing, building, and maintaining robust data pipelines and warehouses. Skilled in ETL/ELT processes, cloud data platforms, and ensuring data quality and availability for analytics teams. Passionate about building scalable data infrastructure that empowers data-driven organisations.`;
  }
  if (t.includes('product manager') || t.includes('product owner')) {
    return `Strategic product manager with experience leading cross-functional teams to define, build, and launch impactful products. Skilled at balancing user needs, business goals, and technical constraints to prioritise the highest-value work. Data-driven approach to decision-making with a consistent focus on measurable outcomes.`;
  }
  if (t.includes('designer') || t.includes('ux') || t.includes('ui/ux') || t.includes('product designer')) {
    return `Creative UX/UI designer passionate about crafting intuitive digital experiences that solve real user problems. Skilled in user research, wireframing, prototyping, and translating insights into compelling visual designs. Proficient in Figma with a strong track record of working collaboratively in fast-paced product teams.`;
  }
  if (t.includes('project manager') || t.includes('programme manager')) {
    return `Experienced project manager with a track record of delivering complex projects on time and within budget. Skilled in stakeholder management, risk mitigation, and fostering high-performing teams. Comfortable operating across both waterfall and agile methodologies to drive results in diverse environments.`;
  }
  if (t.includes('marketing') || t.includes('growth')) {
    return `Results-focused marketing professional with expertise in digital marketing, brand strategy, and customer acquisition. Experienced in running data-driven campaigns across social media, email, SEO, and paid channels to drive measurable growth and ROI.`;
  }
  if (t.includes('finance') || t.includes('accountant') || t.includes('financial analyst') || t.includes('cfo')) {
    return `Finance professional with expertise in financial analysis, reporting, and strategic planning. Skilled in building financial models, managing budgets, and presenting insights to senior leadership. Committed to accuracy, compliance, and supporting data-driven business decisions.`;
  }
  if (t.includes('hr') || t.includes('human resource') || t.includes('people') || t.includes('talent')) {
    return `Dedicated HR professional with experience in talent acquisition, employee engagement, and organisational development. Passionate about building inclusive workplaces and equipping teams with the tools they need to thrive. Skilled in aligning people strategies with business goals.`;
  }
  if (t.includes('sales') || t.includes('business development') || t.includes('account manager')) {
    return `Results-driven sales professional with a proven track record of exceeding targets and building long-term client relationships. Skilled in consultative selling, pipeline management, and cross-functional collaboration. Passionate about creating value for customers and contributing to sustainable revenue growth.`;
  }
  if (t.includes('cybersecurity') || t.includes('security analyst') || t.includes('penetration')) {
    return `Cybersecurity professional with expertise in threat analysis, vulnerability assessment, and incident response. Committed to protecting organisational assets through proactive security measures, compliance frameworks, and security awareness programmes.`;
  }

  // Generic fallback using the provided title
  return `Dedicated ${title} with a proven track record of delivering high-quality results in dynamic environments. Committed to continuous learning, cross-functional collaboration, and leveraging expertise to create meaningful impact. Eager to bring drive, professionalism, and domain knowledge to a forward-thinking organisation.`;
}
